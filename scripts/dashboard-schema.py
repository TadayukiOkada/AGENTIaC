#!/usr/bin/env python3
"""Export the management contract and its TypeScript DTOs without probing any hosts."""
import argparse
import json
from pathlib import Path
import sys

CODE = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(CODE / 'src'))
from agentiac import paths  # noqa: E402
ROOT = paths.root()


def typescript(schema):
    if '$ref' in schema:
        return schema['$ref'].rsplit('/', 1)[-1]
    if 'enum' in schema:
        return ' | '.join(json.dumps(value) for value in schema['enum'])
    if 'const' in schema:
        return json.dumps(schema['const'])
    for union in ('anyOf', 'oneOf'):
        if union in schema:
            return ' | '.join(typescript(member) for member in schema[union])
    kind = schema.get('type')
    if kind == 'array':
        return 'Array<' + typescript(schema.get('items', {})) + '>'
    if kind == 'object':
        properties = schema.get('properties')
        if properties is not None:
            required = set(schema.get('required', []))
            return '{\n' + ''.join('  ' + json.dumps(key) + ('' if key in required else '?') +
                                  ': ' + typescript(value) + '\n'
                                  for key, value in properties.items()) + '}'
        extra = schema.get('additionalProperties', {})
        return 'Record<string, ' + (typescript(extra) if isinstance(extra, dict) else 'unknown') + '>'
    if kind in {'integer', 'number'}:
        return 'number'
    return {'string': 'string', 'boolean': 'boolean', 'null': 'null'}.get(kind, 'unknown')


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args(argv)
    from agentiac.management.app import app
    schema = app.openapi()
    models = schema.get('components', {}).get('schemas', {})
    content = '// Generated by scripts/dashboard-schema.py. Do not edit.\n\n'
    content += '\n\n'.join('export type ' + name + ' = ' + typescript(spec)
                           for name, spec in sorted(models.items())) + '\n'
    outputs = {'dashboard/src/generated/api.ts': content,
               'dashboard/src/generated/openapi.json': json.dumps(schema, indent=2, sort_keys=True) + '\n'}
    mismatch = []
    for name, text in outputs.items():
        path = CODE / name
        if args.check:
            if not path.exists() or path.read_text() != text:
                mismatch.append(name)
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text)
    if mismatch:
        print('Regenerate management contract: ' + ', '.join(mismatch), file=sys.stderr)
        return 1
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
